#!/usr/bin/env node

/**
 * Turns the colors in src/style/brand.css (the NativeWind / shadcn tokens) into a typed
 * palette, written to src/style/palette.generated.ts, so JS code that can't read CSS variables
 * (the navigation theme, the map theme) takes the same colors from the same place.
 *
 * metro.config.js runs it on every Metro start; `bun run build:palette` runs it by hand.
 */

const fs = require("fs");
const path = require("path");

const input = path.join(__dirname, "..", "src", "style", "brand.css");
const output = path.join(__dirname, "..", "src", "style", "palette.generated.ts");

const HSL_TRIPLET = /^(\d+(?:\.\d+)?)\s+(\d+(?:\.\d+)?)%\s+(\d+(?:\.\d+)?)%$/;

/** `0 84.2% 60.2%` (how shadcn writes a color) as `hsl(0, 84.2%, 60.2%)`; null for other values. */
function toHsl(value) {
  const match = HSL_TRIPLET.exec(value.trim());
  return match ? `hsl(${match[1]}, ${match[2]}%, ${match[3]}%)` : null;
}

/** The color variables declared in one CSS block, in order. Non-colors (`--radius`) are skipped. */
function colorsIn(block) {
  const colors = {};
  for (const [, name, value] of block.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) {
    const color = toHsl(value);
    if (color) colors[name] = color;
  }
  return colors;
}

/**
 * Reads the `:root` (light) and `.dark:root` (dark) blocks. Like the CSS cascade, a color the
 * dark block doesn't override keeps its light value.
 */
function parseBrandCss(css) {
  const blocks = {};
  const source = css.replace(/\/\*[\s\S]*?\*\//g, "");
  for (const [, selector, body] of source.matchAll(/(\.dark:root|:root)\s*\{([^}]*)\}/g)) {
    blocks[selector] = colorsIn(body);
  }

  const light = blocks[":root"];
  const dark = blocks[".dark:root"];
  if (!light || !dark) {
    throw new Error("brand.css needs both a `:root` and a `.dark:root` block.");
  }
  const orphan = Object.keys(dark).find((name) => !(name in light));
  if (orphan) throw new Error(`--${orphan} is in .dark:root but not in :root.`);

  return { light, dark: { ...light, ...dark } };
}

function render(palette) {
  const scheme = (colors) =>
    Object.entries(colors)
      .map(([name, color]) => `    ${JSON.stringify(name)}: ${JSON.stringify(color)},`)
      .join("\n");

  return `// Generated by scripts/build-palette.js from src/style/brand.css. Do not edit.
// Add or change a color in brand.css (and tailwind.config.js); Metro regenerates this on start,
// or run \`bun run build:palette\`.
export const PALETTE = {
  light: {
${scheme(palette.light)}
  },
  dark: {
${scheme(palette.dark)}
  },
} as const;

/** A NativeWind color token, as in \`bg-primary\` or \`text-muted-foreground\`. */
export type ColorToken = keyof typeof PALETTE.light;
`;
}

/** Regenerates the palette file; only writes when its content changes. */
function buildPalette() {
  const source = render(parseBrandCss(fs.readFileSync(input, "utf8")));
  const current = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : null;
  if (current !== source) fs.writeFileSync(output, source);
  return source;
}

module.exports = { buildPalette, parseBrandCss, render };

if (require.main === module) {
  buildPalette();
  console.log(`Wrote ${path.relative(process.cwd(), output)}`);
}

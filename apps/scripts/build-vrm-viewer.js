#!/usr/bin/env node

/**
 * Bundles the WebView VRM viewer (src/feature/Avatar/viewer/viewer.ts) into a single HTML
 * string, written to viewer-html.generated.ts. Run it with `bun run build:viewer` after
 * changing viewer.ts or upgrading three / @pixiv/three-vrm / @fanoalone/vrm-controller.
 */

const { spawnSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const viewerDir = path.join(__dirname, "..", "src", "feature", "Avatar", "viewer");
const entry = path.join(viewerDir, "viewer.ts");
const output = path.join(viewerDir, "viewer-html.generated.ts");

const build = spawnSync(
  "bun",
  ["build", entry, "--target=browser", "--format=iife", "--minify"],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);

if (build.status !== 0) {
  console.error(build.stderr || build.error);
  process.exit(build.status ?? 1);
}

// A literal "</script" inside the bundle would end the inline <script> early.
const js = build.stdout.replaceAll("</script", "<\\/script");

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />
<style>
  html, body { margin: 0; height: 100%; overflow: hidden; background: transparent; touch-action: none; }
  canvas { display: block; width: 100%; height: 100%; }
</style>
</head>
<body>
<script>${js}</script>
</body>
</html>`;

fs.writeFileSync(
  output,
  `// Generated by scripts/build-vrm-viewer.js from viewer.ts. Do not edit; run \`bun run build:viewer\`.\n` +
    `export default ${JSON.stringify(html)};\n`,
);

console.log(`Wrote ${path.relative(process.cwd(), output)} (${(html.length / 1024).toFixed(0)} KiB)`);
